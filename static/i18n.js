let currentLang = localStorage.getItem("sc_lang") || "en";
if (!I18N[currentLang]) currentLang = "en";

function t(key, vars) {
  const dict = I18N[currentLang] || I18N.en;
  let s = dict[key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      s = s.replaceAll(`{${k}}`, String(v));
    });
  }
  return s;
}

function tCat(name) {
  if (!name) return t("shop.general");
  const key = `cat.${name}`;
  const translated = t(key);
  return translated === key ? name : translated;
}

function tRole(role) {
  const r = (role || "customer").toLowerCase();
  return r === "admin" ? t("role.admin") : t("role.customer");
}

function getLang() {
  return currentLang;
}

function ensureHiFont() {
  if (document.getElementById("font-hi")) return;
  const link = document.createElement("link");
  link.id = "font-hi";
  link.rel = "stylesheet";
  link.href =
    "https://fonts.googleapis.com/css2?family=Noto+Sans+Devanagari:wght@500;700&display=swap";
  document.head.appendChild(link);
}

function setLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem("sc_lang", lang);
  document.documentElement.lang = lang === "hi" ? "hi" : "en";
  document.title = t("meta.title");
  if (lang === "hi") ensureHiFont();
  applyStaticI18n();
  if (typeof navigate === "function" && typeof state !== "undefined") {
    navigate(state.page || "shop");
  }
}

function applyStaticI18n() {
  const sub = document.querySelector(".brand-sub");
  if (sub) sub.textContent = t("brand.sub");
  const brand = document.getElementById("brand-home");
  if (brand) brand.title = t("brand.goShop");

  const map = {
    shop: "nav.shop",
    orders: "nav.orders",
    admin: "nav.admin",
    catalog: "nav.catalog",
  };
  document.querySelectorAll(".nav-btn[data-page]").forEach((btn) => {
    const page = btn.dataset.page;
    if (page === "cart") {
      const badge = btn.querySelector("#cart-badge");
      btn.childNodes.forEach((n) => {
        if (n.nodeType === Node.TEXT_NODE) n.textContent = `${t("nav.cart")} `;
      });
      if (!btn.querySelector("#cart-badge") && badge) btn.appendChild(badge);
      // Rebuild label safely
      const count = badge ? badge.textContent : "";
      const hidden = badge && badge.classList.contains("hidden");
      btn.innerHTML = `${t("nav.cart")} <span id="cart-badge" class="nav-badge${hidden ? " hidden" : ""}">${count || ""}</span>`;
      return;
    }
    if (page === "account") return; // renderChrome sets this
    if (map[page]) btn.textContent = t(map[page]);
  });

  document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.langBtn === currentLang);
  });
}

